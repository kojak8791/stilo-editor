import { describe, expect, it } from 'vitest';
import { defaultExtensions } from '.';

describe('defaultExtensions', () => {
  it('returns the implemented default extensions', () => {
    expect(defaultExtensions().map((ext) => ext.name)).toEqual([
      'doc',
      'text',
      'paragraph',
      'heading',
      'blockquote',
      'codeBlock',
      'horizontalRule',
      'hardBreak',
      'image',
      'table',
      'bulletList',
      'orderedList',
      'listItem',
      'taskList',
      'taskItem',
      'bold',
      'italic',
      'underline',
      'strike',
      'subscript',
      'superscript',
      'code',
      'link',
      'textStyle',
      'highlight',
      'textAlign',
      'lineHeight',
      'clearFormatting',
      'textCase',
      'history',
      'moveBlock',
      'placeholder',
      'search',
      'dropCursor',
      'gapCursor',
    ]);
  });

  it('leaves out the extensions set to false', () => {
    expect(defaultExtensions({ bold: false }).map((ext) => ext.name)).toEqual([
      'doc',
      'text',
      'paragraph',
      'heading',
      'blockquote',
      'codeBlock',
      'horizontalRule',
      'hardBreak',
      'image',
      'table',
      'bulletList',
      'orderedList',
      'listItem',
      'taskList',
      'taskItem',
      'italic',
      'underline',
      'strike',
      'subscript',
      'superscript',
      'code',
      'link',
      'textStyle',
      'highlight',
      'textAlign',
      'lineHeight',
      'clearFormatting',
      'textCase',
      'history',
      'moveBlock',
      'placeholder',
      'search',
      'dropCursor',
      'gapCursor',
    ]);
  });
});
